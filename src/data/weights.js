/** Power bracket for weight-ratio moves (Heavy Slam, Heat Crash) */
export function weightRatioPower(attackerWeight, defenderWeight) {
  const ratio = attackerWeight / defenderWeight;
  if (ratio >= 5) return 120;
  if (ratio >= 4) return 100;
  if (ratio >= 3) return 80;
  if (ratio >= 2) return 60;
  return 40;
}

/** Power bracket for defender-weight moves (Grass Knot, Low Kick) */
export function weightBracketPower(defenderWeight) {
  if (defenderWeight >= 200) return 120;
  if (defenderWeight >= 100) return 100;
  if (defenderWeight >=  50) return 80;
  if (defenderWeight >=  25) return 60;
  if (defenderWeight >=  10) return 40;
  return 20;
}
